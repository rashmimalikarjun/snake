import { chromium } from 'playwright'
const b = await chromium.launch()
const page = await b.newPage({ viewport: { width: 900, height: 1200 } })
page.on('pageerror', e => console.log('PAGEERROR:', String(e)))
page.on('console', m => console.log('CONSOLE:', m.type(), m.text()))
await page.goto('http://localhost:5173/', { waitUntil: 'networkidle' })
console.log('--- menu body ---')
console.log((await page.textContent('body')).slice(0, 400))
console.log('--- pressing Enter ---')
await page.keyboard.press('Enter')
await page.waitForTimeout(800)
console.log('canvas count:', await page.locator('canvas').count())
console.log('--- body after enter ---')
console.log((await page.textContent('body')).slice(0, 400))
await page.screenshot({ path: '/tmp/after-enter.png', fullPage: true })
// click the SNAKE XENZIA menu button directly
await page.getByRole('button', { name: /SNAKE XENZIA/ }).click().catch(e=>console.log('click fail', e.message))
await page.waitForTimeout(800)
console.log('canvas count after click:', await page.locator('canvas').count())
await page.screenshot({ path: '/tmp/after-click.png', fullPage: true })
await b.close()
